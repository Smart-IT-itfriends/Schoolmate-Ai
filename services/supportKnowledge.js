function formatDailySpinRewards(config) {
  const rewards = config?.dailySpin?.rewards || [];
  if (!rewards.length) {
    return '• +10 XP, +25 XP, +50 XP, 🧊 заморозка стріку або нічого';
  }
  return rewards.map((item) => `• ${item.label}`).join('\n');
}

